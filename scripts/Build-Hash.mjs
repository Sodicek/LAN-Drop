import { build } from 'esbuild';
import { mkdir, copyFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
await mkdir(root + 'src/LanDrop/wwwroot/vendor', {recursive:true});
await build({absWorkingDir:root, entryPoints:['scripts/hash-entry.js'], bundle:true,
  format:'iife', target:'safari16', minify:true, legalComments:'inline',
  banner:{js:'/*! @noble/hashes 2.4.0, MIT; see sha256.LICENSE.txt. Generated by npm run build:hash. */'},
  outfile:'src/LanDrop/wwwroot/vendor/sha256.js'});
await copyFile(root + 'node_modules/@noble/hashes/LICENSE', root + 'src/LanDrop/wwwroot/vendor/sha256.LICENSE.txt');
