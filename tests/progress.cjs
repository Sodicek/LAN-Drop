const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = {clock:0};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/LanDrop/wwwroot/progress.js'),'utf8')+'\nglobalThis.Meter=TransferMeter;',context);
const meter = new context.Meter(1000,()=>context.clock);
assert.equal(meter.sample(0).remainingSeconds,null);
context.clock=1000;
const first=meter.sample(250);
assert.equal(first.percent,25);
assert.equal(first.speed,250);
assert.equal(first.remainingSeconds,3);
context.clock=2000;
const stalled=meter.sample(250);
assert.equal(stalled.speed,125);
assert.equal(stalled.remainingSeconds,6);
assert.equal(meter.sample(100).loaded,250,'Late events cannot reverse progress');
assert.equal(meter.sample(2000).percent,100,'Clamp completed bytes');
assert.equal(meter.sample(NaN).loaded,1000,'Ignore malformed progress');
const empty=new context.Meter(0,()=>context.clock);
assert.equal(empty.sample(0).percent,100);
assert.equal(empty.sample(0).speed,0);
console.log('Progress checks passed: estimates, stalls, late events, completion and empty files.');
