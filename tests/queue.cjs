const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = {};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/LanDrop/wwwroot/queue.js'),'utf8')+'\nglobalThis.Queue=TransferQueue;',context);
const files = [{name:'saved.jpg'}, {name:'interrupted.jpg'}, {name:'waiting.jpg'}];
const queue = new context.Queue(files);
const first = queue.items[0], second = queue.items[1];
queue.transition(first,'transferring');
assert.equal(queue.remaining().length,3, 'Sending bytes cannot mark a file complete');
queue.transition(first,'completed');
queue.transition(second,'failed','connection lost');
const retry = queue.remaining();
assert.equal(retry.length,2);
assert.equal(retry[0].file,files[1], 'Retry retains actual File reference');
assert.equal(retry[1].file,files[2]);
queue.transition(first,'failed');
assert.equal(first.state,'completed', 'Completed receipts cannot be retried');
queue.transition(second,'waiting');
assert.equal(second.error,null,'A new attempt clears the previous error');
queue.transition({},'completed');
assert.equal(queue.remaining().length,2,'An unrelated item cannot change the queue');
queue.transition(second,'completed');
queue.transition(queue.items[2],'completed');
assert.equal(queue.remaining().length,0);
console.log('PASS: retries retain unfinished File references, omit completed receipts, preserve completion, and reset attempt errors.');
